const classifiedEntries = Object.entries(classifiedTools).flatMap(
  ([permission, names]) =>
    names.map((name) => [name, permission as McpPermission] as const),
);
export const BUILT_IN_MCP_PERMISSIONS: ReadonlyMap<string, McpPermission> =
  new Map(classifiedEntries);
if (BUILT_IN_MCP_PERMISSIONS.size !== classifiedEntries.length) {
  throw new Error(
    "Built-in MCP tools must have exactly one permission classification",
  );
}

export function requiredMcpScopes(
  name: string,
  external = false,
): readonly string[] {
  const permission = external
    ? "destructive"
    : (BUILT_IN_MCP_PERMISSIONS.get(name) ?? "destructive");
  return MCP_PERMISSION_SCOPES[permission];
}

export type McpSecurityScheme = "oauth2" | "noauth";

export function mcpScopeMetadata(
  name: string,
  external = false,
  authentication: McpSecurityScheme = "oauth2",
) {
  const scopes = [...requiredMcpScopes(name, external)];
  return {
    "aide/requiredScopes": scopes,
    securitySchemes:
      authentication === "noauth"
        ? [{ type: "noauth" as const }]
        : [{ type: "oauth2" as const, scopes }],
  };
}
